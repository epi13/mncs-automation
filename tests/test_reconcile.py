class ReconcileFlowTests(ReconcileCase):
    @need_mncs
    @need_doc
    def test_stale_regenerates_then_converges(self) -> None:
        self.write_fixture("generation 4 status")
        first = tick(canonical_gen=5, observed_gen=4)
        self.assertEqual(first["action"], codes.RECON_REGENERATE)
        self.assertTrue(self.apply("generation 5 status"))
        rendered = self.document.read_text(encoding="utf-8")
        self.assertIn("generation 5 status", rendered)

        adopted = adopt(observed=4, regenerated=5, canonical=5)
        self.assertTrue(adopted["accept"])
        self.assertEqual(adopted["new_observed"], 5)

        second = tick(canonical_gen=5, observed_gen=adopted["new_observed"])
        self.assertEqual(second["action"], codes.RECON_UP_TO_DATE)
        before = self.document.read_bytes()
        self.assertTrue(self.apply("generation 5 status", check=True))
        self.assertEqual(before, self.document.read_bytes())

    @need_mncs
    @need_doc
    def test_failed_verification_withholds_regeneration(self) -> None:
        self.write_fixture("generation 4 status")
        decision = tick(canonical_gen=6, observed_gen=4,
                        verdict=codes.VERDICT_FAIL)
        self.assertEqual(decision["action"],
                         codes.RECON_FAILED_VERIFICATION)
        self.assertFalse(decision["publish"])
        # The reconciler performs no regeneration while gated.
        self.assertIn("generation 4 status",
                      self.document.read_text(encoding="utf-8"))
        released = tick(canonical_gen=6, observed_gen=4,
                        verdict=codes.VERDICT_PASS)
        self.assertEqual(released["action"], codes.RECON_REGENERATE)

    @need_mncs
    @need_doc
    def test_duplicate_event_regenerates_once(self) -> None:
        self.write_fixture("generation 4 status")
        first = tick(canonical_gen=5, observed_gen=4)
        self.assertEqual(first["action"], codes.RECON_REGENERATE)
        self.assertTrue(self.apply("generation 5 status"))
        adopted = adopt(observed=4, regenerated=5, canonical=5)
        settled = self.document.read_bytes()
        # The same canonical event observed again changes nothing.
        replay = tick(canonical_gen=5, observed_gen=adopted["new_observed"])
        self.assertEqual(replay["action"], codes.RECON_UP_TO_DATE)
        self.assertEqual(settled, self.document.read_bytes())

    @need_mncs
    @need_doc
    def test_interrupted_regeneration_recovers_without_duplicates(self) -> None:
        self.write_fixture("generation 5 status")
        before_crash = tick(canonical_gen=6, observed_gen=5)
        self.assertEqual(before_crash["action"], codes.RECON_REGENERATE)
        # Crash after regenerating but before adopting: bytes are
        # rewritten deterministically and observed never advances.
        self.assertTrue(self.apply("generation 6 status"))
        after_restart = tick(canonical_gen=6, observed_gen=5)
        self.assertEqual(after_restart["action"], codes.RECON_REGENERATE)
        self.assertTrue(self.apply("generation 6 status"))
        adopted = adopt(observed=5, regenerated=6, canonical=6)
        self.assertTrue(adopted["accept"])
        converged = tick(canonical_gen=6,
                         observed_gen=adopted["new_observed"])
        self.assertEqual(converged["action"], codes.RECON_UP_TO_DATE)
        # A stale regeneration replayed after convergence is refused.
        stale = adopt(observed=6, regenerated=5, canonical=6)
        self.assertFalse(stale["accept"])
        self.assertEqual(stale["reason"], codes.RECON_ADOPT_REGRESSION)
        self.assertEqual(stale["new_observed"], 6)

    @need_mncs
    def test_observed_ahead_blocks_without_publish(self) -> None:
        decision = tick(canonical_gen=5, observed_gen=6, unpublished=9,
                        threshold=3, oldest_unpublished_ms=1_000,
                        now_ms=9_000, max_latency_ms=1_000)
        self.assertEqual(decision["action"], codes.RECON_BLOCKED)
        self.assertEqual(decision["reason"],
                         codes.RECON_REASON_OBSERVED_AHEAD)
        self.assertFalse(decision["publish"])

    @need_mncs
    @need_doc
    def test_human_prose_regions_remain_untouched(self) -> None:
        head = "# Titre — with unicode déjà ✓\n\nFirst § paragraph.\n\n"
        tail = "\nLast ¶ paragraph — fin.\n"
        self.write_fixture("old", prose_head=head, prose_tail=tail)
        decision = tick(canonical_gen=5, observed_gen=4)
        self.assertEqual(decision["action"], codes.RECON_REGENERATE)
        self.assertTrue(self.apply("new"))
        rendered = self.document.read_text(encoding="utf-8")
        self.assertTrue(rendered.startswith(head))
        self.assertTrue(rendered.endswith(tail))
        self.assertIn("\nnew\n", rendered)

    @need_mncs
    def test_publish_threshold_fires_once_per_receipt(self) -> None:
        key = ("sha256:artifact", "target:mock", "external:1")
        decision = tick(canonical_gen=5, observed_gen=5, unpublished=3,
                        threshold=3)
        self.assertTrue(decision["publish"])
        self.assertTrue(self.record_receipt(key, 5))
        # The duplicate publication event finds the receipt and writes
        # nothing; with nothing unpublished the tick goes quiet.
        self.assertFalse(self.record_receipt(key, 5))
        quiet = tick(canonical_gen=5, observed_gen=5, unpublished=0,
                     threshold=3)
        self.assertFalse(quiet["publish"])
        lines = self.receipts.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), 1)

    @need_mncs
    @need_store_receipt
    def test_receipt_identity_is_the_dedup_key(self) -> None:
        def receipt(artifact: int, target: int, external: int,
                    generation: int, evidence: int) -> list[int]:
            out = [80, 82, 1, 0] + [artifact] * 32 + [target] * 32
            out += [external] * 32
            out += [(generation >> shift) & 0xFF
                    for shift in (56, 48, 40, 32, 24, 16, 8, 0)]
            return out + [evidence] * 32

        def same(left: list[int], right: list[int]) -> bool:
            assert MNCS is not None
            document = native.call_function(
                mncs=MNCS, program=str(STORE_RECEIPT),
                module="store.receipt.v1", function="same_publication",
                args=[{"sequence": {"values": [{"byte": {"value": v}}
                                                    for v in left]}},
                      {"sequence": {"values": [{"byte": {"value": v}}
                                                    for v in right]}}],
                libraries=LIBRARIES)
            return bool(document["call"]["returned"][0]["boolean"]["value"])

        original = receipt(11, 12, 13, 7, 14)
        rerecorded = receipt(11, 12, 13, 9, 15)
        other = receipt(11, 12, 16, 7, 14)
        self.assertTrue(same(original, rerecorded))
        self.assertFalse(same(original, other))


