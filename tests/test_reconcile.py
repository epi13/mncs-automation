"""End-to-end projection reconciliation across mncs-automation and mncs-doc.

A canonical generation advances, the native reconcile tick marks the
projection stale, mncs-doc applies regenerated bytes to the document's
machine-owned region, adoption advances the observed generation, and a
second tick converges without duplicating work. Verification verdicts
gate authoritative claims; interruption recovers without duplicates;
stale generations never overwrite newer output.

Time is injected everywhere; no test touches the network or the real
clock. Skipped cleanly when the compiler binary or the sibling
mncs-doc checkout is absent.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
import sys

sys.path.insert(0, str(REPO / "tools"))

from automation import codes, native  # noqa: E402

WORKSPACE = REPO.parent
DOC_REPO = WORKSPACE / "mncs-doc"
PROJECT_CLI = DOC_REPO / "tools" / "project.py"
STORE_RECEIPT = (WORKSPACE / "mncs-store" / "src" / "store"
                 / "receipt.mncs")


def find_mncs() -> str | None:
    for candidate in (
        os.environ.get("MNCS_BIN"),
        os.environ.get("MNCS_BINARY"),
        str(WORKSPACE / "mncs-language" / "target" / "debug" / "mncs"),
    ):
        if candidate and Path(candidate).is_file():
            return candidate
    return None


MNCS = find_mncs()
LIBRARIES = [str(WORKSPACE / "mncs-test" / "native"),
             str(REPO / "native")]


def need_mncs(test):
    return unittest.skipIf(MNCS is None, "mncs binary unavailable")(test)


def need_doc(test):
    return unittest.skipIf(not PROJECT_CLI.is_file(),
                           "mncs-doc projection CLI unavailable")(test)


def need_store_receipt(test):
    return unittest.skipIf(not STORE_RECEIPT.is_file(),
                           "mncs-store receipt module unavailable")(test)


def tick(**fields: Any) -> dict[str, Any]:
    base = {"canonical_gen": 5, "observed_gen": 5,
            "verdict": codes.VERDICT_PASS, "require_verified": 1,
            "unpublished": 0, "threshold": 0,
            "oldest_unpublished_ms": 0, "now_ms": 9_000,
            "max_latency_ms": 0}
    base.update(fields)
    assert MNCS is not None
    return native.reconcile_tick(mncs=MNCS, libraries=LIBRARIES, **base)


def adopt(observed: int, regenerated: int, canonical: int) -> dict[str, Any]:
    assert MNCS is not None
    return native.adopt_observed(
        mncs=MNCS, libraries=LIBRARIES, observed_gen=observed,
        regenerated_gen=regenerated, canonical_gen=canonical)


class ReconcileCase(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="reconcile-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.document = self.tmp / "README.md"
        self.generated = self.tmp / "generated.md"
        self.receipts = self.tmp / "receipts.jsonl"

    def write_fixture(self, region_body: str, prose_head: str = "# Title\n\n",
                      prose_tail: str = "\nHuman outro.\n") -> None:
        self.document.write_text(
            f"{prose_head}<!-- MNCS:generated:begin -->\n{region_body}\n"
            f"<!-- MNCS:generated:end -->{prose_tail}", encoding="utf-8")

    def apply(self, body: str, check: bool = False,
              create: bool = False) -> bool:
        self.generated.write_text(body, encoding="utf-8")
        assert MNCS is not None
        command = [sys.executable, str(PROJECT_CLI), "project-apply",
                   "--document", str(self.document),
                   "--generated", str(self.generated),
                   "--sources", "2", "--template-present", "1",
                   "--mncs-bin", MNCS]
        if create:
            command.append("--create")
        if check:
            command.append("--check")
        completed = subprocess.run(command, capture_output=True, text=True,
                                   timeout=180)
        return completed.returncode == 0

    def record_receipt(self, key: tuple[str, str, str],
                       generation: int) -> bool:
        """Append a receipt unless this publication key already has one."""
        existing = set()
        if self.receipts.exists():
            for line in self.receipts.read_text(encoding="utf-8").splitlines():
                entry = json.loads(line)
                existing.add((entry["artifact"], entry["target"],
                              entry["external"]))
        if key in existing:
            return False
        with self.receipts.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps({"artifact": key[0], "target": key[1],
                                     "external": key[2],
                                     "canonical_generation": generation,
                                     "schema_version":
                                     "mncs.publication-receipt/1"}) + "\n")
        return True


class NativeReconcileCodeTests(unittest.TestCase):
    @need_mncs
    def test_codes_match_native(self) -> None:
        program = str(REPO / "native" / "mncs" / "automation"
                      / "reconcile.mncs")
        module = "mncs.automation.reconcile.v1"

        def call(function: str, args: list) -> Any:
            assert MNCS is not None
            document = native.call_function(
                mncs=MNCS, program=program, module=module,
                function=function, args=args, libraries=LIBRARIES)
            return document["call"]["returned"][0]["integer"]["value"]

        for function, expected in (
                ("verdict_fail", codes.VERDICT_FAIL),
                ("verdict_pass", codes.VERDICT_PASS),
                ("verdict_unknown", codes.VERDICT_UNKNOWN)):
            self.assertEqual(call(function, []), expected)
        for variant, expected in (
                ("UpToDate", codes.RECON_UP_TO_DATE),
                ("Regenerate", codes.RECON_REGENERATE),
                ("AwaitVerification", codes.RECON_AWAIT_VERIFICATION),
                ("Blocked", codes.RECON_BLOCKED),
                ("FailedVerification", codes.RECON_FAILED_VERIFICATION)):
            self.assertEqual(
                call("action_code", [{"finite": {"type": "ReconAction",
                                                "variant": variant}}]),
                expected)
        for variant, expected in (
                ("Current", codes.RECON_REASON_CURRENT),
                ("CanonicalAdvanced",
                 codes.RECON_REASON_CANONICAL_ADVANCED),
                ("VerificationUnknown",
                 codes.RECON_REASON_VERIFICATION_UNKNOWN),
                ("VerificationFailed",
                 codes.RECON_REASON_VERIFICATION_FAILED),
                ("ObservedAhead", codes.RECON_REASON_OBSERVED_AHEAD)):
            self.assertEqual(
                call("reason_code", [{"finite": {"type": "ReconReason",
                                                "variant": variant}}]),
                expected)


